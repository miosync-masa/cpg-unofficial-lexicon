"""Pull by form type, conditions C and D (exploratory; docs/analysis_plan_form_type.md).

Usage: python3 analysis/analyze_form_type.py

Inputs : results/items_final.csv (v1.1 consensus form_type), embeddings/results/nnpm_DE_<model>.csv (pull_C_k10,
         pull_D_k10, raw tradition).
Outputs: results/form_type_pull.json, results/form_type_pull.md (with --unrounded: results/form_type_pull_unrounded.json only)

Per condition and model: n, mean, SD by form type; pull ~ form_type + (1 | tradition), REML, existing_form as the
reference; coefficient of transparent_combination with one-sided Wald p (b > 0) and 95% Wald CI; Holm across the
three models within each condition. A fit that does not converge is recorded, not replaced. "converged" is the
optimizer's flag; statsmodels' ConvergenceWarnings (e.g. "MLE may be on the boundary", which the intercept-only fits
of H-C1 and H-D1 also give) are stored beside it with the tradition variance.
"""
import json
import sys
import warnings
from pathlib import Path

import pandas as pd
import statsmodels.formula.api as smf
from scipy import stats
from statsmodels.stats.multitest import multipletests
from statsmodels.tools.sm_exceptions import ConvergenceWarning

ROOT = Path(__file__).resolve().parents[1]
MODELS = {"text_embedding_3_large": "OpenAI text-embedding-3-large", "BAAI_bge_m3": "BAAI/bge-m3",
          "gemini_embedding_001": "gemini-embedding-001"}
LEVELS = ["existing_form", "transparent_combination"]
N = {"C": 94, "D": 67}
# --unrounded: the same results without rounding, for the supplement tables (analysis/make_si.py), which need the
# unrounded value where a stored 4-decimal value is half-way at the precision of the main text
UNROUNDED = "--unrounded" in sys.argv
r4 = (lambda x: float(x)) if UNROUNDED else (lambda x: round(float(x), 4))

ft = pd.read_csv(ROOT / "results/items_final.csv", encoding="utf-8").set_index("item_id").form_type
out = {"plan": "docs/analysis_plan_form_type.md", "exploratory": True, "conditions": {}}
for X in ["C", "D"]:
    rows = []
    for tag, name in MODELS.items():
        d = pd.read_csv(ROOT / f"embeddings/results/nnpm_DE_{tag}.csv", encoding="utf-8-sig")
        d = d.dropna(subset=[f"pull_{X}_k10"]).assign(form_type=lambda x: x.item_id.map(ft))
        assert len(d) == N[X], (X, tag, len(d))
        other = d[~d.form_type.isin(LEVELS)]
        d = d[d.form_type.isin(LEVELS)]
        y = f"pull_{X}_k10"
        desc = {lv: {"n": int((d.form_type == lv).sum()), "mean": r4(d.loc[d.form_type == lv, y].mean()),
                     "sd": r4(d.loc[d.form_type == lv, y].std(ddof=1))} for lv in LEVELS}
        with warnings.catch_warnings(record=True) as w:
            warnings.simplefilter("always", ConvergenceWarning)
            m = smf.mixedlm(f"{y} ~ C(form_type, Treatment('existing_form'))", d, groups=d["tradition"]).fit(reml=True)
        term = "C(form_type, Treatment('existing_form'))[T.transparent_combination]"
        b, se = m.params[term], m.bse[term]
        rows.append({"model": name, "n": int(len(d)), "n_other_form_type_left_out": int(len(other)),
                     "n_traditions": int(d.tradition.nunique()), "by_form_type": desc,
                     "b_transparent": r4(b), "se": r4(se), "z": r4(b / se), "p_one_sided": r4(stats.norm.sf(b / se)),
                     "ci95": [r4(b - 1.96 * se), r4(b + 1.96 * se)],
                     "converged": bool(m.converged), "var_tradition": r4(m.cov_re.iloc[0, 0]),
                     "warnings": sorted({str(x.message) for x in w if issubclass(x.category, ConvergenceWarning)}),
                     "_p": float(stats.norm.sf(b / se))})
    holm = multipletests([r["_p"] for r in rows], method="holm")[1]
    for r, ph in zip(rows, holm):
        r["p_holm"] = r4(ph)
        r.pop("_p")
        r["reading"] = ("prediction holds" if r["b_transparent"] > 0 and ph < .05 else
                        "predicted direction, not shown" if r["b_transparent"] > 0 else "prediction does not hold")
    out["conditions"][X] = {"n_items": N[X], "per_model": rows,
                            "n_models_prediction_holds": sum(r["reading"] == "prediction holds" for r in rows)}
if UNROUNDED:
    json.dump(out, open(ROOT / "results/form_type_pull_unrounded.json", "w"), indent=1, ensure_ascii=False)
    sys.exit(0)
json.dump(out, open(ROOT / "results/form_type_pull.json", "w"), indent=1, ensure_ascii=False)

md = ["# Pull by form type (exploratory; generated by analysis/analyze_form_type.py)", "",
      "Plan: docs/analysis_plan_form_type.md. Mixed model pull ~ form_type + (1 | tradition), REML, existing_form "
      "as reference; one-sided Wald p for transparent_combination > existing_form; Holm across the three models."]
for X, lab in [("C", "Condition C (main set, n = 94)"), ("D", "Condition D (n = 67)")]:
    c = out["conditions"][X]
    md += ["", f"## {lab}", "",
           "| model | existing_form n | mean (SD) | transparent_combination n | mean (SD) | b [95% CI] | z | p one-sided "
           "| p Holm | converged | var(tradition) | reading |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in c["per_model"]:
        e, t = r["by_form_type"]["existing_form"], r["by_form_type"]["transparent_combination"]
        md.append(f"| {r['model']} | {e['n']} | {e['mean']:.4f} ({e['sd']:.4f}) | {t['n']} | {t['mean']:.4f} "
                  f"({t['sd']:.4f}) | {r['b_transparent']:.4f} [{r['ci95'][0]:.4f}, {r['ci95'][1]:.4f}] | "
                  f"{r['z']:.2f} | {r['p_one_sided']:.4f} | {r['p_holm']:.4f} | {r['converged']} | {r['var_tradition']:.4f} | {r['reading']} |")
    md += ["", f"Models where the prediction holds: {c['n_models_prediction_holds']} of 3. Items with another "
           f"form type left out: {c['per_model'][0]['n_other_form_type_left_out']}.",
           "Warnings: " + "; ".join(f"{r['model']}: {', '.join(r['warnings']) or 'none'}" for r in c["per_model"])]
(ROOT / "results/form_type_pull.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("\n".join(md))
